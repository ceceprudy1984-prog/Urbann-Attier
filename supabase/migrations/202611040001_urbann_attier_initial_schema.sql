-- Jalankan hanya pada project Supabase khusus Urbann Attier.

begin;

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users as admins
    where admins.user_id = (select auth.uid())
      and admins.is_active = true
  );
$$;

revoke all on function private.is_admin() from public, anon;
grant execute on function private.is_admin() to authenticated;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text unique,
  slug text not null unique,
  name text not null,
  category text,
  description text not null default '',
  material text,
  model text,
  care_notes text,
  price_retail bigint check (price_retail is null or price_retail >= 0),
  price_series bigint check (price_series is null or price_series >= 0),
  price_wholesale bigint check (price_wholesale is null or price_wholesale >= 0),
  wholesale_min_qty integer not null default 20 check (wholesale_min_qty >= 1),
  is_active boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_variants (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products (id) on delete cascade,
  color_name text not null,
  sku text unique,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, color_name),
  unique (id, product_id)
);

create table if not exists public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products (id) on delete cascade,
  variant_id uuid not null,
  image_path text not null,
  alt_text text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  foreign key (variant_id, product_id)
    references public.product_variants (id, product_id) on delete cascade
);

create table if not exists public.product_sizes (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products (id) on delete cascade,
  size_name text not null,
  bust_cm numeric(6, 2),
  garment_length_cm numeric(6, 2),
  sleeve_length_cm numeric(6, 2),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, size_name),
  unique (id, product_id),
  check (bust_cm is null or bust_cm >= 0),
  check (garment_length_cm is null or garment_length_cm >= 0),
  check (sleeve_length_cm is null or sleeve_length_cm >= 0)
);

create table if not exists public.inventory (
  product_id bigint not null,
  variant_id uuid not null,
  size_id uuid not null,
  stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  updated_at timestamptz not null default now(),
  primary key (variant_id, size_id),
  foreign key (variant_id, product_id)
    references public.product_variants (id, product_id) on delete cascade,
  foreign key (size_id, product_id)
    references public.product_sizes (id, product_id) on delete cascade
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  address_line text not null,
  province text not null,
  city text not null,
  district text not null,
  postal_code text not null,
  customer_note text,
  status text not null default 'needs_confirmation'
    check (status in ('needs_confirmation', 'awaiting_payment', 'paid', 'processing', 'shipped', 'completed', 'cancelled')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'waiting_confirmation', 'paid', 'rejected', 'refunded')),
  payment_method text not null default 'whatsapp_manual',
  shipping_status text not null default 'waiting_quote'
    check (shipping_status in ('waiting_quote', 'ready_to_ship', 'shipped', 'delivered', 'returned')),
  shipping_provider text,
  shipping_service text,
  tracking_number text,
  subtotal_amount bigint not null default 0 check (subtotal_amount >= 0),
  packaging_fee bigint not null default 0 check (packaging_fee >= 0),
  shipping_fee bigint check (shipping_fee is null or shipping_fee >= 0),
  total_amount bigint check (total_amount is null or total_amount >= 0),
  confirmed_at timestamptz,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete restrict,
  product_id bigint references public.products (id) on delete set null,
  variant_id uuid references public.product_variants (id) on delete set null,
  size_id uuid references public.product_sizes (id) on delete set null,
  product_name text not null,
  color_name text not null,
  size_name text not null,
  purchase_mode text not null check (purchase_mode in ('ecer', 'seri-warna', 'seri-ukuran')),
  pricing_tier text not null check (pricing_tier in ('ecer', 'serian', 'grosir')),
  quantity integer not null check (quantity > 0),
  unit_price bigint not null check (unit_price >= 0),
  line_total bigint not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete restrict,
  provider text not null default 'manual',
  payment_method text,
  status text not null default 'pending'
    check (status in ('pending', 'paid', 'failed', 'expired', 'refunded')),
  amount bigint not null check (amount >= 0),
  provider_transaction_id text,
  payment_reference text,
  proof_image_path text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, provider_transaction_id)
);

create table if not exists public.store_public_settings (
  id smallint primary key default 1 check (id = 1),
  shop_name text not null default 'Urbann Attier',
  whatsapp_number text,
  packaging_fee bigint not null default 5000 check (packaging_fee >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_private_settings (
  id smallint primary key default 1 check (id = 1),
  origin_address text,
  origin_district text,
  origin_city text,
  origin_province text,
  origin_postal_code text,
  updated_at timestamptz not null default now()
);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger products_set_updated_at before update on public.products
for each row execute function private.set_updated_at();
create trigger product_variants_set_updated_at before update on public.product_variants
for each row execute function private.set_updated_at();
create trigger product_sizes_set_updated_at before update on public.product_sizes
for each row execute function private.set_updated_at();
create trigger inventory_set_updated_at before update on public.inventory
for each row execute function private.set_updated_at();
create trigger orders_set_updated_at before update on public.orders
for each row execute function private.set_updated_at();
create trigger payments_set_updated_at before update on public.payments
for each row execute function private.set_updated_at();
create trigger store_public_settings_set_updated_at before update on public.store_public_settings
for each row execute function private.set_updated_at();
create trigger store_private_settings_set_updated_at before update on public.store_private_settings
for each row execute function private.set_updated_at();

create index if not exists products_active_order_idx on public.products (is_active, sort_order);
create index if not exists product_variants_product_idx on public.product_variants (product_id, sort_order);
create index if not exists product_images_variant_idx on public.product_images (variant_id, sort_order);
create index if not exists product_sizes_product_idx on public.product_sizes (product_id, sort_order);
create index if not exists inventory_product_idx on public.inventory (product_id);
create index if not exists orders_status_created_idx on public.orders (status, created_at desc);
create index if not exists orders_phone_created_idx on public.orders (customer_phone, created_at desc);
create index if not exists order_items_order_idx on public.order_items (order_id);
create index if not exists payments_order_idx on public.payments (order_id, created_at desc);

alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.product_variants enable row level security;
alter table public.product_images enable row level security;
alter table public.product_sizes enable row level security;
alter table public.inventory enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.payments enable row level security;
alter table public.store_public_settings enable row level security;
alter table public.store_private_settings enable row level security;

revoke all on public.admin_users, public.products, public.product_variants,
  public.product_images, public.product_sizes, public.inventory, public.orders,
  public.order_items, public.payments, public.store_public_settings,
  public.store_private_settings from public, anon, authenticated;

grant select on public.products, public.product_variants, public.product_images,
  public.product_sizes, public.inventory, public.store_public_settings
  to anon, authenticated;
grant insert, update, delete on public.products, public.product_variants,
  public.product_images, public.product_sizes, public.inventory,
  public.store_public_settings to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;
grant select, insert, update, delete on public.admin_users to authenticated;
grant select, insert, update on public.orders, public.order_items, public.payments,
  public.store_private_settings to authenticated;

create policy admin_users_select_self on public.admin_users
for select to authenticated
using (user_id = (select auth.uid()) or (select private.is_admin()));
create policy admin_users_manage_admins on public.admin_users
for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy products_public_read on public.products
for select to anon, authenticated
using (is_active = true);
create policy products_admin_manage on public.products
for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy product_variants_public_read on public.product_variants
for select to anon, authenticated
using (
  is_active = true and exists (
    select 1 from public.products as p
    where p.id = product_variants.product_id and p.is_active = true
  )
);
create policy product_variants_admin_manage on public.product_variants
for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy product_images_public_read on public.product_images
for select to anon, authenticated
using (exists (
  select 1
  from public.product_variants as v
  join public.products as p on p.id = v.product_id
  where v.id = product_images.variant_id
    and v.is_active = true and p.is_active = true
));
create policy product_images_admin_manage on public.product_images
for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy product_sizes_public_read on public.product_sizes
for select to anon, authenticated
using (exists (
  select 1 from public.products as p
  where p.id = product_sizes.product_id and p.is_active = true
));
create policy product_sizes_admin_manage on public.product_sizes
for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy inventory_public_read on public.inventory
for select to anon, authenticated
using (exists (
  select 1
  from public.product_variants as v
  join public.products as p on p.id = v.product_id
  where v.id = inventory.variant_id
    and v.is_active = true and p.is_active = true
));
create policy inventory_admin_manage on public.inventory
for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy orders_admin_read on public.orders
for select to authenticated using ((select private.is_admin()));
